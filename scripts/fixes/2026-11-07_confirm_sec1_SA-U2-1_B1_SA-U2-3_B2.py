def index_confirm(ids):
    p = "raw/json/question_index.json"; s = open(p, encoding="utf-8").read(); n = 0
    for q in ids:
        i = s.index(f'"moduleId": "{q}"'); a = s.rfind("{", 0, i); j = s.index("}", i)
        obj = s[a:j + 1]; o2 = obj.replace('"problemStatus": "draft"', '"problemStatus": "confirmed"')
        if o2 != obj: s = s[:a] + o2 + s[j + 1:]; n += 1
    json.loads(s); open(p, "w", encoding="utf-8", newline="").write(s); return n

BQ_MIS = re.compile(r"^> \*\*常見誤讀[^*]*\*\*[：:]\s*(.*)$", re.M)
BQ_NOTE = re.compile(r"^> \*\*本解記號\*\*[：:]\s*(.*)$", re.M)

def new_sec1(qid, d, own, old_mis, old_note):
    rows = "\n".join(f"| {a} | {b} | {c} |" for a, b, c in d["mis"])
    head = "## §1 題目（考卷原文見題目正本）" if qid == "SA-2025-3" else "## 1. 題目（考卷原文見題目正本）"
    t = (f"\n{head}\n\n"
         f"> 考卷原文、公式／附表、附圖與判讀清單（已確認）見 [`{qid}-problem.md`]({qid}-problem.md)。本節只列解題時最容易讀錯的地方與本解使用的記號；題意以題目正本為準。\n\n"
         f"![{qid} 重繪題目附圖：{d['alt']}](figs/{qid}-fig-1-problem.svg)\n*重繪自考卷附圖，{d['cap']}*\n\n")
    if d.get("extra"): t += d["extra"] + "\n"
    t += f"### 常見誤讀\n| 項目 | 正確判讀 | 常見誤讀 |\n|---|---|---|\n{rows}\n"
    if old_mis: t += f"\n**本解舊版曾犯：** {old_mis}\n"
    t += f"\n**本解記號：** {old_note or d.get('note', NOTE)}\n"
    if own:
        t += "\n### 判讀圖解（解析自繪）\n\n" + "\n".join(o[0].strip() + "\n" for o in own)
    return t + "\n---\n"

def rewrite(qid):
    p = f"raw/solutions/{qid}/{qid}.md"; s = open(p, encoding="utf-8").read()
    if "題目（考卷原文見題目正本）" in s: return False
    d = Q[qid]; prob = open(f"raw/solutions/{qid}/{qid}-problem.md", encoding="utf-8").read()
    own = []; extra = ""
    if qid == "SA-2018-3":
        old = "\n## 1. 基本設定與物理判斷\n"; assert s.count(old) == 1
        s = s.replace(old, new_sec1(qid, d, [], None, None) + "\n## 1.5 基本設定與物理判斷\n", 1)
        extra = "；原解析無題目重述，新增 §1（首次引用證據圖見題目正本），原 §1「基本設定與物理判斷」改為 §1.5"
    else:
        m = re.search(r"\n## (§?)1[\.\s][^\n]*\n(.*?)(?=\n## )", s, re.S); assert m, qid
        old = m.group(2)
        for png in re.findall(r"\(([^)]+\.png)\)", old):
            assert os.path.basename(png) in prob, (qid, png)
        own = re.findall(r"(!\[[^\]]*\]\((figs/[^)]+\.svg)\)\s*\n(?:\s*\n)?(?:\*[^\n]*\*\s*\n)?)", old + "\n")
        mm = BQ_MIS.search(old); mn = BQ_NOTE.search(old)
        s = s[:m.start()] + new_sec1(qid, d, own, mm and mm.group(1).strip(), mn and mn.group(1).strip()) + s[m.end():]
        if mm: extra += "；原 §1 的勘誤引言併入「本解舊版曾犯」"
    if qid == "SA-2025-3":
        o = "§1 圖說寫的「$\\theta_A$、$\\theta_B$ 逆時針為正」與上述牴觸。"
        assert s.count(o) == 1, qid
        s = s.replace(o, "舊版 §1 圖說（2026-11-07 已改為指向題目正本）寫的「$\\theta_A$、$\\theta_B$ 逆時針為正」與上述牴觸。")
    gen = f"gen_{qid}_problem.py" if qid in EXIST else f"gen_{qid}.py"
    figs = f"figs/{qid}-fig-1-problem.svg" + ("、figs/SA-2022-1-fig-2-problem.svg" if qid == "SA-2022-1" else "")
    what = f"§1 改為指向題目正本並放重繪附圖（{figs}）、加常見誤讀"
    if own: what += "；原 §1 解析自繪圖移至「判讀圖解（解析自繪）」"
    s = s.rstrip("\n") + f"\n\n*修正日期：{DATE}（{what}{extra}；圖由 {gen} 產生，可重跑）*\n"
    open(p, "w", encoding="utf-8", newline="\n").write(s); return True

